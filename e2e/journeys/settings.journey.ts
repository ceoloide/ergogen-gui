import type { Page } from '@playwright/test';
import { pasteIntoEditor } from './app';
import { test, expect } from './journey';

const config = `points:
  zones:
    matrix:
      columns:
        left:
        right:
      rows:
        bottom:
        top:
outlines:
  plate:
    - what: rectangle
      where: true
      size: 14
pcbs:
  board:
    outlines:
      edge:
        outline: plate
`;

const downloadOutput = (page: Page, file: string) =>
  page.getByLabel(`Download ${file}`, { exact: true });
const outputNames = (page: Page) =>
  page
    .getByLabel(/^Download .+\.\w+$/)
    .evaluateAll((controls) =>
      controls.map((control) =>
        control.getAttribute('aria-label')?.replace(/^Download /, '')
      )
    );
const pcbAnd3dSwitch = (page: Page) =>
  page.getByRole('checkbox', {
    name: 'Enable auto-generate PCB and 3D (slow)',
  });

test('generates as the settings and the feature flags of the address say', async ({
  page,
  journey,
}) => {
  const errorBanner = page.getByRole('button', { name: 'Close error message' });
  const skippedOutlines = page.getByText(
    'Custom outlines were skipped because the respective feature flags are disabled in settings.',
    { exact: true }
  );
  await page.context().grantPermissions(['clipboard-read', 'clipboard-write']);

  await journey.step('Open the app', async () => {
    await page.goto('/');
    await expect(
      page.getByRole('heading', { name: 'Ergogen Web UI' })
    ).toBeVisible();
  });

  await journey.step('Choose Empty Configuration', async () => {
    await page
      .getByRole('button', { name: 'Start with empty configuration' })
      .click();
    await expect(
      page.getByRole('textbox', { name: 'Editor content' })
    ).toBeAttached();
  });

  await journey.step('Turn off Auto-generate PCB & 3D', async () => {
    await page.getByRole('button', { name: 'Show settings panel' }).click();
    await expect(pcbAnd3dSwitch(page)).toBeChecked();
    await page.getByText('Auto-generate PCB & 3D', { exact: true }).click();
    await expect(pcbAnd3dSwitch(page)).not.toBeChecked();
    await page.getByRole('button', { name: 'Hide settings panel' }).click();
  });

  await journey.step('Paste the outline plate and the PCB board', async () => {
    await pasteIntoEditor(page, config);
    await expect(downloadOutput(page, 'plate.dxf')).toBeVisible({
      timeout: 30_000,
    });
    await expect(errorBanner).toBeHidden();
    // The generation that made plate.dxf left out the PCB.
    await expect(
      downloadOutput(page, 'board.kicad_pcb'),
      'the PCB, which automatic generation leaves out while Auto-generate PCB & 3D is off'
    ).toBeHidden();
    journey.observe('autoGenerated', await outputNames(page));
  });

  await journey.step('Choose Generate', async () => {
    await page.getByRole('button', { name: 'Generate configuration' }).click();
    await expect(downloadOutput(page, 'board.kicad_pcb')).toBeVisible({
      timeout: 30_000,
    });
    await expect(errorBanner).toBeHidden();
    journey.observe('generated', await outputNames(page));
  });

  await journey.step('Reload the page', async () => {
    await page.reload();
    await expect(
      page.getByRole('textbox', { name: 'Editor content' })
    ).toBeAttached({ timeout: 30_000 });
    await page.getByRole('button', { name: 'Show settings panel' }).click();
    await expect(
      pcbAnd3dSwitch(page),
      'Auto-generate PCB & 3D after the reload'
    ).not.toBeChecked();
  });

  await journey.step('Add a custom outline in the settings', async () => {
    await page.getByRole('button', { name: 'Outlines', exact: true }).click();
    await page.getByRole('button', { name: 'Add new custom outline' }).click();
    await expect(
      page.getByRole('link', { name: 'download injection custom_outline_1' })
    ).toBeVisible();
  });

  await journey.step('Open the address with ?ff_outlines=false', async () => {
    await page.goto('/?ff_outlines=false');
    await expect(skippedOutlines).toBeVisible({ timeout: 30_000 });
    await page.getByRole('button', { name: 'Show settings panel' }).click();
    await expect(
      page.getByRole('button', { name: 'Footprints', exact: true })
    ).toBeVisible();
    await expect(
      page.getByRole('button', { name: 'Outlines', exact: true })
    ).toBeHidden();
    journey.observe('query', new URL(page.url()).search);
  });
});
